"""Rasterizes DejaVu Sans Mono (the font MetaCodex ships, Bitstream Vera licence) into mcx_font.h: ASCII 32-126,
one 8-bit coverage atlas, for mcx::Text. Usage: python3 native/xr/tools/make-font.py (needs Pillow; PC only)."""
import os
from PIL import Image, ImageDraw, ImageFont
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
font = ImageFont.truetype(os.path.join(root, "unity/Assets/MetaCodex/Fonts/DejaVuSansMono.ttf"), 26)
W, H = 16, 32  # cell
asc, desc = font.getmetrics()
chars = [chr(c) for c in range(32, 127)]
atlas = Image.new("L", (W * len(chars), H), 0)
d = ImageDraw.Draw(atlas)
for i, ch in enumerate(chars):
    d.text((i * W, (H - asc - desc) // 2), ch, font=font, fill=255)
data = atlas.tobytes()
out = os.path.join(root, "native/xr/mcx_font.h")
with open(out, "w") as f:
    f.write("// Generated by native/xr/tools/make-font.py from DejaVu Sans Mono (Bitstream Vera licence; DejaVu changes are\n"
            "// public domain): ASCII 32-126, %dx%d cells, 8-bit coverage. Do not edit.\n#pragma once\n" % (W, H))
    f.write("#define MCX_FONT_W %d\n#define MCX_FONT_H %d\n#define MCX_FONT_FIRST 32\n#define MCX_FONT_COUNT %d\n" % (W, H, len(chars)))
    f.write("static const unsigned char kMcxFont[%d] = {\n" % len(data))
    for i in range(0, len(data), 32):
        f.write(",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(out, len(data), "bytes")
